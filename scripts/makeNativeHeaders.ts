import fs from 'fs'
import path from 'path'

import {
  API_KEY_PLACEHOLDER,
  readEmbeddedSignerApiKey,
  signerOutputsExist
} from './makeApiSigner'

function writeEdgeApiKeyFiles(apiKey: string): void {
  // Same printable-ASCII rule as makeApiSigner: quotes/backslashes would break
  // the Swift/Java string literals below if we only JSON-escaped for C.
  if (!/^[\x20-\x7e]+$/.test(apiKey)) {
    throw new Error('edgeKey.json apiKey must be printable ASCII')
  }
  const escapedApiKey = apiKey.replace(/\\/g, '\\\\').replace(/"/g, '\\"')

  let pushServer = 'https://push2.edge.app'
  try {
    pushServer = require('../src/theme/appConfig.js').notificationServers[0]
  } catch (e) {}
  const escapedPushServer = pushServer
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')

  const iosPath = path.join(__dirname, '../ios/EdgeApiKey.swift')
  fs.writeFileSync(
    iosPath,
    `/* auto-generated by scripts/makeNativeHeaders.ts */

public class EdgeApiKey {
  public static let apiKey = "${escapedApiKey}"
  public static let pushServer = "${escapedPushServer}"
}
`
  )

  const androidPath = path.join(
    __dirname,
    '../android/app/src/main/java/co/edgesecure/app/EdgeApiKey.java'
  )
  fs.writeFileSync(
    androidPath,
    `/* auto-generated by scripts/makeNativeHeaders.ts */
package co.edgesecure.app;

public class EdgeApiKey {
  public static final String apiKey = "${escapedApiKey}";
  public static final String pushServer = "${escapedPushServer}";
}
`
  )
}

/**
 * Called from makeApiSigner when it emits a stub: EdgeApiKey must advertise
 * the same placeholder the C sources embed, even if older headers exist.
 */
export function writeStubEdgeApiKeyHeaders(): void {
  writeEdgeApiKeyFiles(API_KEY_PLACEHOLDER)
  console.log('wrote EdgeApiKey.swift/java stub apiKey (lockstep with signer)')
}

function makeNativeHeaders(): void {
  // Match makeApiSigner stub policy: never pair a real public apiKey with a
  // missing apiSecret, or EdgeCore push and EdgeApiSigner login disagree.
  let apiKey = API_KEY_PLACEHOLDER
  let hasSecret = false
  try {
    const edgeKey = require('../edgeKey.json')
    hasSecret =
      typeof edgeKey.apiSecret === 'string' && edgeKey.apiSecret !== ''
    const hasKey = typeof edgeKey.apiKey === 'string' && edgeKey.apiKey !== ''
    if (hasSecret && hasKey) apiKey = edgeKey.apiKey
    else console.log(apiKey)
  } catch (e) {
    console.log(apiKey)
  }

  const iosPath = path.join(__dirname, '../ios/EdgeApiKey.swift')
  const androidPath = path.join(
    __dirname,
    '../android/app/src/main/java/co/edgesecure/app/EdgeApiKey.java'
  )
  // When the signer kept a complete tree, sync EdgeApiKey from the embedded
  // C apiKey whenever either header is missing — never invent the placeholder
  // while native login still exposes a real edge_api_key().
  if (!hasSecret && signerOutputsExist()) {
    const iosExists = fs.existsSync(iosPath)
    const androidExists = fs.existsSync(androidPath)
    if (iosExists && androidExists) {
      console.log(
        'warn: apiSecret missing; keeping existing EdgeApiKey.swift/java'
      )
      return
    }
    const embedded = readEmbeddedSignerApiKey()
    if (embedded != null) {
      console.log(
        'warn: apiSecret missing; restoring EdgeApiKey from embedded signer apiKey'
      )
      writeEdgeApiKeyFiles(embedded)
      return
    }
  }

  writeEdgeApiKeyFiles(apiKey)
}

if (require.main === module) {
  try {
    makeNativeHeaders()
  } catch (e) {
    console.log(e)
  }
}
